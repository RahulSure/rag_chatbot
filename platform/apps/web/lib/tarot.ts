export const DECK: TarotCard[] = [
  ...MAJOR.map(([name, ke, kh, me, mh], i) => {
    const n = String(i).padStart(2, "0");
    return { id: `major-${n}`, name, image: `/images/tarot/major-${n}.jpg`, keywords: [ke, kh], meaning: [me, mh] } as TarotCard;
  }),
  ...SUITS.flatMap((suit) =>
    suit.rows.map(([ke, kh, me, mh], i) => {
      const n = String(i + 1).padStart(2, "0");
      return {
        id: `${suit.file}-${n}`,
        name: `${RANKS[i]} of ${suit.name}`,
        image: `/images/tarot/${suit.file}-${n}.jpg`,
        keywords: [ke, kh],
        meaning: [me, mh],
      } as TarotCard;
    }),
  ),
];

export const cardById = (id: string) => DECK.find((c) => c.id === id);

/** A fair shuffle using the browser's cryptographic random source. */
export function shuffled<T>(items: T[]): T[] {
  const out = [...items];
  const rand = new Uint32Array(out.length);
  crypto.getRandomValues(rand);
  for (let i = out.length - 1; i > 0; i--) {
    const j = rand[i] % (i + 1);
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

